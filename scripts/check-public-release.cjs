const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const manifest = JSON.parse(fs.readFileSync('release-manifest.json', 'utf8'));
for (const [file, digest] of Object.entries(manifest.sha256)) assert.equal(crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'),digest,file);
const html = fs.readFileSync('physical-ai/index.html','utf8');
assert.match(html, /assets\/index-[^" ]+\.js/);
assert.match(fs.readFileSync('physical-ai/how-it-works.html','utf8'), /Every research and workspace view is available without sign-in/);
assert.ok(manifest.publicRoutes.length >= 11);
console.log(`Verified release from ${manifest.sourceCommit}, ${Object.keys(manifest.sha256).length} hashes, ${manifest.publicRoutes.length} public routes`);
